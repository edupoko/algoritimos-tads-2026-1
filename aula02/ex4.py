#Calcular média de quatro números

num1 = int(input("Digite o primeiro num: "))
num2 = int(input("Digite o segundo num: "))
num3 = int(input("Digite o terceiro num: "))
num4 = int(input("Digite o quarto num: "))

media = num1 + num2 + num3 + num4 / 4

print(f"A média dos números digitados é igual a {media}")